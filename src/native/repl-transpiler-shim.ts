// Bun.Transpiler's replMode (claude-code 2.1.326 code mode) and scanImports. the contract, taken from the
// REPL tool's chunk, which runs `new Bun.Transpiler({ loader: "js", replMode: true }).transformSync(code)`
// and then re-parses the output:
//
//   the output must be only top-level `var name;` declarations without initializers, then one statement
//   that calls a parameterless arrow or function expression with no arguments; anything else makes every
//   script fail with "a fault in the tool". every top-level declaration of the input, and every var in a
//   block or for head outside a function, is hoisted into those `var` names, because the tool reads them to
//   refuse a script that would overwrite a global, and because only they persist on the vm context between
//   scripts
//   the call's promise resolves to `{ __proto__: null, value: <completion> }` when the script ends in an
//   expression, an initialized declaration, or a class; the tool unwraps `value`, and its stack quoting
//   expects `__proto__: null,` and `value: …` on their own lines
//   a syntax error throws an error whose `position` is { line, column (1-based), lineText }
//   scanImports(code) -> [{ kind, path }] with kind "import-statement", "dynamic-import", or "require-call";
//   the tool refuses any of them before transforming
export const REPL_TRANSPILER_SHIM = [
  "function __cccParseProgram(source, sourceType) {",
  '  return __baseRequire("acorn").parse(source, { ecmaVersion: "latest", sourceType, allowAwaitOutsideFunction: true, allowHashBang: true });',
  "}",
  "function __cccReplSyntaxError(error, source) {",
  '  const failure = new SyntaxError(String(error?.message ?? error).replace(/ \\(\\d+:\\d+\\)$/, ""));',
  "  const location = error?.loc;",
  '  if (typeof location?.line === "number" && typeof location.column === "number") {',
  '    failure.position = { line: location.line, column: location.column + 1, lineText: source.split("\\n")[location.line - 1] ?? "" };',
  "  }",
  "",
  "  return failure;",
  "}",
  "function __cccBindingNames(pattern) {",
  "  switch (pattern.type) {",
  '    case "Identifier":',
  "      return [pattern.name];",
  '    case "ObjectPattern":',
  '      return pattern.properties.flatMap((property) => __cccBindingNames(property.type === "RestElement" ? property.argument : property.value));',
  '    case "ArrayPattern":',
  "      return pattern.elements.flatMap((element) => (element === null ? [] : __cccBindingNames(element)));",
  '    case "AssignmentPattern":',
  "      return __cccBindingNames(pattern.left);",
  '    case "RestElement":',
  "      return __cccBindingNames(pattern.argument);",
  "    default:",
  '      throw new TypeError("unexpected binding pattern " + pattern.type);',
  "  }",
  "}",
  "// a sequence expression needs parentheses wherever an assignment expression is expected: as an initializer",
  "// value and as the completion's property value",
  "function __cccParenthesizeSequence(expression, text) {",
  '  if (expression.type === "SequenceExpression") return "(" + text(expression) + ")";',
  "  return text(expression);",
  "}",
  "function __cccAssignmentText(declarator, text) {",
  '  const assignment = text(declarator.id) + " = " + __cccParenthesizeSequence(declarator.init, text);',
  "",
  "  // at the start of a statement, an object pattern's { would open a block",
  '  if (declarator.id.type === "ObjectPattern") return "(" + assignment + ")";',
  "  return assignment;",
  "}",
  "// functions and class static blocks keep their own var scope",
  "const __cccVarScopeNodeTypes = /^(?:FunctionDeclaration|FunctionExpression|ArrowFunctionExpression|StaticBlock)$/;",
  "// bun hoists a var nested in a block, a switch case, or a for head out to the script and rewrites it in place as",
  "// assignments. it leaves a var in an unbraced body such as `if (c) var x` local and unhoisted, and a for head's var",
  "// without initializers in place while still hoisting its names. position is the parent's type and the key holding",
  "// the declaration",
  "function __cccNestedVarReplacement(position, declaration, text) {",
  "  const assignments = declaration.declarations.filter((declarator) => declarator.init !== null).map((declarator) => __cccAssignmentText(declarator, text));",
  "  switch (position) {",
  '    case "ForInStatement.left":',
  '    case "ForOfStatement.left":',
  "      return text(declaration.declarations[0].id);",
  '    case "ForStatement.init":',
  "      if (assignments.length === 0) return text(declaration);",
  '      return assignments.join(", ");',
  '    case "BlockStatement.body":',
  '    case "SwitchCase.consequent":',
  '      return assignments.map((assignment) => assignment + ";").join(" ");',
  "    default:",
  "      return undefined;",
  "  }",
  "}",
  "function __cccNestedVarRewrites(node, text) {",
  "  return Object.entries(node).flatMap(([key, value]) =>",
  "    (Array.isArray(value) ? value : [value]).flatMap((child) => {",
  '      if (child === null || typeof child !== "object" || typeof child.type !== "string") return [];',
  "      if (__cccVarScopeNodeTypes.test(child.type)) return [];",
  '      if (child.type !== "VariableDeclaration" || child.kind !== "var") return __cccNestedVarRewrites(child, text);',
  "",
  '      const replacement = __cccNestedVarReplacement(node.type + "." + key, child, text);',
  "      if (replacement === undefined) return [];",
  "",
  "      return [{ start: child.start, end: child.end, text: replacement, names: child.declarations.flatMap((declarator) => __cccBindingNames(declarator.id)) }];",
  "    }),",
  "  );",
  "}",
  "function __cccSliceWithRewrites(source, node, rewrites) {",
  '  let text = "";',
  "  let cursor = node.start;",
  "  for (const rewrite of rewrites) {",
  "    text += source.slice(cursor, rewrite.start) + rewrite.text;",
  "    cursor = rewrite.end;",
  "  }",
  "",
  "  return text + source.slice(cursor, node.end);",
  "}",
  "// like bun, a script that starts with { and does not end with ; is one object literal expression when it parses as",
  "// one; otherwise it is read as statements, where bun reports a syntax error",
  "function __cccObjectLiteralCompletion(source) {",
  "  if (!/^\\s*\\{/.test(source) || /;\\s*$/.test(source)) return undefined;",
  "",
  '  const wrapped = "(" + source + "\\n)";',
  "  let program;",
  "  try {",
  '    program = __cccParseProgram(wrapped, "script");',
  "  } catch {",
  "    return undefined;",
  "  }",
  "",
  "  const [statement] = program.body;",
  '  const isOneExpression = program.body.length === 1 && statement.type === "ExpressionStatement" && statement.start === 0 && statement.end === wrapped.length;',
  "  if (!isOneExpression) return undefined;",
  "",
  "  return wrapped;",
  "}",
  "// bun takes the completion from the last statement that emits something: an empty statement and a declaration",
  "// without initializers emit nothing",
  "function __cccEmitsNothing(statement) {",
  '  if (statement.type === "EmptyStatement") return true;',
  '  return statement.type === "VariableDeclaration" && statement.declarations.every((declarator) => declarator.init === null);',
  "}",
  "function __cccReplOutput(names, statements, completion) {",
  '  const lines = [...new Set(names)].map((name) => "var " + name + ";");',
  '  lines.push("(async () => {", ...statements);',
  "",
  "  if (completion !== undefined) {",
  '    lines.push("return {", "  __proto__: null,", "  value: " + completion, "};");',
  "  }",
  "",
  '  lines.push("})();");',
  "",
  '  return lines.join("\\n");',
  "}",
  "function __cccReplTransform(source) {",
  "  const objectLiteral = __cccObjectLiteralCompletion(source);",
  "  if (objectLiteral !== undefined) return __cccReplOutput([], [], objectLiteral);",
  "",
  "  let program;",
  "  try {",
  '    program = __cccParseProgram(source, "script");',
  "  } catch (error) {",
  "    throw __cccReplSyntaxError(error, source);",
  "  }",
  "",
  "  const text = (node) => source.slice(node.start, node.end);",
  "  const completionStatement = program.body.findLast((statement) => !__cccEmitsNothing(statement));",
  "  const names = [];",
  "  const functionAssignments = [];",
  "  const statements = [];",
  "  let completion;",
  "  for (const statement of program.body) {",
  "    const isCompletion = statement === completionStatement;",
  '    if (statement.type === "VariableDeclaration") {',
  "      const initialized = statement.declarations.filter((declarator) => declarator.init !== null);",
  "      const completionDeclarator = isCompletion ? initialized.at(-1) : undefined;",
  "      names.push(...statement.declarations.flatMap((declarator) => __cccBindingNames(declarator.id)));",
  "      for (const declarator of initialized) {",
  "        if (declarator === completionDeclarator) {",
  "          completion = __cccAssignmentText(declarator, text);",
  "        } else {",
  '          statements.push(__cccAssignmentText(declarator, text) + ";");',
  "        }",
  "      }",
  '    } else if (statement.type === "FunctionDeclaration") {',
  "      names.push(statement.id.name);",
  '      functionAssignments.push(statement.id.name + " = " + text(statement) + ";");',
  '    } else if (statement.type === "ClassDeclaration") {',
  "      names.push(statement.id.name);",
  '      const assignment = statement.id.name + " = " + text(statement);',
  "      if (isCompletion) {",
  "        completion = assignment;",
  "      } else {",
  '        statements.push(assignment + ";");',
  "      }",
  '    } else if (statement.type === "ExpressionStatement" && isCompletion) {',
  "      completion = __cccParenthesizeSequence(statement.expression, text);",
  "    } else {",
  "      // a function declared in a block stays as written, so sloppy-mode hoisting makes it visible to the rest of the",
  "      // script; bun scopes it to its block. neither keeps it for the next script",
  "      const rewrites = __cccNestedVarRewrites(statement, text);",
  "      names.push(...rewrites.flatMap((rewrite) => rewrite.names));",
  "      // a copied statement can end without a semicolon, and the declaration that followed it may now be gone, moved",
  "      // to the top, or start with ( or [; without the added ; the next emitted line would continue the statement",
  "      const statementText = __cccSliceWithRewrites(source, statement, rewrites);",
  '      statements.push(statementText.endsWith(";") ? statementText : statementText + ";");',
  "    }",
  "  }",
  "",
  "  return __cccReplOutput(names, [...functionAssignments, ...statements], completion);",
  "}",
  "// like bun, a dynamic import or require call counts only when its specifier is a string or a template without",
  "// substitutions, and require only with that one argument",
  "function __cccStaticImportRecord(kind, specifier) {",
  '  if (specifier.type === "Literal" && typeof specifier.value === "string") return { kind, path: specifier.value };',
  '  if (specifier.type === "TemplateLiteral" && specifier.expressions.length === 0) return { kind, path: specifier.quasis[0].value.cooked };',
  "  return undefined;",
  "}",
  "function __cccImportRecord(node) {",
  '  const isReexport = (node.type === "ExportNamedDeclaration" || node.type === "ExportAllDeclaration") && node.source !== null;',
  '  if (node.type === "ImportDeclaration" || isReexport) return { kind: "import-statement", path: node.source.value };',
  "",
  '  if (node.type === "ImportExpression") return __cccStaticImportRecord("dynamic-import", node.source);',
  "",
  '  const isRequireCall = node.type === "CallExpression" && node.callee.type === "Identifier" && node.callee.name === "require" && node.arguments.length === 1;',
  '  if (isRequireCall) return __cccStaticImportRecord("require-call", node.arguments[0]);',
  "",
  "  return undefined;",
  "}",
  "function __cccImportRecords(node) {",
  "  if (Array.isArray(node)) return node.flatMap(__cccImportRecords);",
  '  if (node === null || typeof node !== "object" || typeof node.type !== "string") return [];',
  "",
  "  const record = __cccImportRecord(node);",
  "  const childRecords = Object.values(node).flatMap(__cccImportRecords);",
  "  if (record === undefined) return childRecords;",
  "",
  "  return [record, ...childRecords];",
  "}",
  "function __cccScanImports(source) {",
  "  let program;",
  "  try {",
  '    program = __cccParseProgram(source, "module");',
  "  } catch {",
  '    program = __cccParseProgram(source, "script");',
  "  }",
  "",
  "  return __cccImportRecords(program.body);",
  "}",
].join("\n");
